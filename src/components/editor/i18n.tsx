const Ctx = createContext<{ lang: UiLang; t: Dict; setLang: (l: UiLang) => void }>({ lang: "en", t: EN, setLang: () => undefined });

export function UiLangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<UiLang>("en");
  useEffect(() => {
    let l: UiLang | null = null;
    try {
      const v = localStorage.getItem("sls-ui-lang");
      if (v === "es" || v === "en") l = v;
    } catch {}
    setLangState(l ?? (navigator.language?.toLowerCase().startsWith("es") ? "es" : "en"));
  }, []);
  const setLang = (l: UiLang) => {
    setLangState(l);
    try {
      localStorage.setItem("sls-ui-lang", l);
    } catch {}
  };
  return <Ctx.Provider value={{ lang, t: lang === "es" ? ES : EN, setLang }}>{children}</Ctx.Provider>;
}

export const useUi = () => useContext(Ctx);
